// Builds the footer wordmark from Geist Pixel's own glyphs, so the pixel type is one family:
//
//   node scripts/wordmark-from-geist-pixel.mjs   (needs the wawoff2 and opentype.js dev dependencies)
//
// Geist Pixel draws every glyph as separate square cells on a 38-unit grid. This reads the cells of "jsrt"
// from the shipped public/fonts/geist-pixel-latin.woff2, lays the letters out by their own advances and
// writes src/components/ui/wordmark-cells.ts: one SVG path of separate squares (y down from the cap top),
// with the hairline gaps between cells drawn in, plus the size of the grid. Re-run it after changing the
// font file, and commit the output.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const wawoff2 = require('wawoff2')
const opentype = require('opentype.js')

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const WORD = 'jsrt'
const CELL = 38

const woff2 = readFileSync(join(ROOT, 'public/fonts/geist-pixel-latin.woff2'))
const ttf = await wawoff2.decompress(woff2)
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength))
const capTop = Math.round(font.tables.os2.sCapHeight / CELL) // the row just above the cap height

// Each contour is one cell: closed subpaths of a pixel glyph, bounds snapped to the grid.
const bounds = (commands) => {
  const contours = []
  let current = null
  for (const c of commands) {
    if (c.type === 'M') current = [{ x: c.x, y: c.y }]
    else if (current && c.type !== 'Z') current.push({ x: c.x, y: c.y })
    else if (current && c.type === 'Z') {
      contours.push(current)
      current = null
    }
  }
  if (current) contours.push(current)
  return contours.map((pts) => ({
    minX: Math.min(...pts.map((p) => p.x)),
    maxX: Math.max(...pts.map((p) => p.x)),
    minY: Math.min(...pts.map((p) => p.y)),
    maxY: Math.max(...pts.map((p) => p.y)),
  }))
}

const cells = new Set()
let penX = 0
for (const ch of WORD) {
  const glyph = font.charToGlyph(ch)
  if (!glyph || glyph.name === '.notdef') throw new Error(`${ch}: no glyph in the font`)
  for (const b of bounds(glyph.path.commands)) {
    const col = Math.round(b.minX / CELL) + penX
    const row = capTop - Math.round(b.maxY / CELL)
    if (Math.round((b.maxX - b.minX) / CELL) !== 1 || Math.round((b.maxY - b.minY) / CELL) !== 1) {
      throw new Error(`${ch}: a contour is not one cell; the font is not the pixel instance this expects`)
    }
    cells.add(`${col},${row}`)
  }
  penX += Math.round(glyph.advanceWidth / CELL)
}

const grid = [...cells].map((c) => c.split(',').map(Number))
const minRow = Math.min(...grid.map(([, r]) => r))
const maxRow = Math.max(...grid.map(([, r]) => r))
const minCol = Math.min(...grid.map(([c]) => c))
const width = Math.max(...grid.map(([c]) => c)) - minCol + 1
const height = maxRow - minRow + 1

// Each cell is its own square, 9 units on a 10-unit grid: the hairline between cells is in the geometry, so the
// wordmark needs no mask (a mask over a large element is expensive to paint). After the first square every move
// is relative to the last, which keeps the path short and compresses well.
const UNIT = 10
const SIZE = 9
const parts = []
let prev = null
for (const [col, row] of grid
  .map(([c, r]) => [c - minCol, r - minRow])
  .sort((a, b) => a[1] - b[1] || a[0] - b[0])) {
  const x = col * UNIT
  const y = row * UNIT
  parts.push(
    prev === null
      ? `M${x} ${y}h${SIZE}v${SIZE}h-${SIZE}z`
      : `m${x - prev[0]} ${y - prev[1]}h${SIZE}v${SIZE}h-${SIZE}z`,
  )
  prev = [x, y]
}

const out = join(ROOT, 'src/components/ui/wordmark-cells.ts')
writeFileSync(
  out,
  '// Generated by scripts/wordmark-from-geist-pixel.mjs from public/fonts/geist-pixel-latin.woff2. Do not edit.\n' +
    `// "${WORD}" in Geist Pixel: ${cells.size} cells on a ${width} x ${height} grid, each a ${SIZE}-unit square on a\n` +
    `// ${UNIT}-unit pitch (the gap between cells is in the path); row 0 is the cap top.\n` +
    'export const wordmark = {\n' +
    `  width: ${width * UNIT},\n` +
    `  height: ${height * UNIT},\n` +
    `  capRows: ${capTop - minRow + 1},\n` +
    `  path: '${parts.join('')}',\n` +
    '}\n',
)
console.log(`${out.replace(`${ROOT}/`, '')}: ${cells.size} cells, ${width} x ${height}, path ${parts.join('').length} characters`)
